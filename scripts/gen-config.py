#!/usr/bin/env python3
"""Generate the broker config and the example tfvars from config/site-values.yaml.

Single source of truth: config/site-values.yaml.
Outputs:
  hcs-broker.yaml                       (csb serve --config hcs-broker.yaml)
  examples/<service>/provision.tfvars   (direct OpenTofu runs)
"""
import json
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
VALUES_FILE = ROOT / "config" / "site-values.yaml"
BROKER_CONFIG = ROOT / "hcs-broker.yaml"

SERVICES = ["csms"]

# Per-service convention values that rarely change per site; emitted into the
# instance section so every required variable is covered.
CONVENTION_DEFAULTS = {
    "csms": {},
}


def tf(v):
    """Render a python value as an HCL literal."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, list):
        return "[" + ", ".join(tf(i) for i in v) + "]"
    return json.dumps(str(v))


def kv(key, value, comment=None):
    line = f"{key} = {tf(value)}"
    if comment:
        line += f"  # {comment}"
    return line


HEADER = """# -----------------------------------------------------------------------------
# {title}
# GENERATED by scripts/gen-config.py from config/site-values.yaml — edit that
# file and run `make gen-config` instead of editing this one.
# Run:  cd terraform/{svc}/{mod}
#       tofu init
#       tofu plan  -var-file=../../../examples/shared.tfvars -var-file=../../../examples/{svc}/{mod}.tfvars
#       tofu apply -var-file=../../../examples/shared.tfvars -var-file=../../../examples/{svc}/{mod}.tfvars
# Auth: export HCS_ACCESS_KEY=... HCS_SECRET_KEY=...   (or IAM user/password)
#       export HCS_INSECURE=true                        (self-signed certs)
# -----------------------------------------------------------------------------
"""

SIZING_KEYS = {
    "csms": ["secret_name"],
}

OPTIONAL_NOTES = {
    "csms": [
        '# secret_text = "..."                            # optional; random when omitted',
        '# kms_key_id  = "..."                            # optional; default KMS key when omitted',
    ],
}


def gen_provision_tfvars(v, svc):
    inst = v["instances"][svc]
    lines = [HEADER.format(title=f"csb-hcs-{svc} — provision", svc=svc, mod="provision")]

    lines.append("# --- secret ---")
    for key in SIZING_KEYS[svc]:
        lines.append(kv(key, inst[key]))
    lines.append("")

    sizing_keys = set(SIZING_KEYS[svc])
    merged = {**CONVENTION_DEFAULTS[svc], **inst}
    extra = {k: v2 for k, v2 in merged.items() if k not in sizing_keys}
    if extra:
        lines.append("# --- instance ---")
        for key, value in extra.items():
            lines.append(kv(key, value))
        lines.append("")

    lines.extend(OPTIONAL_NOTES[svc])
    if OPTIONAL_NOTES[svc]:
        lines.append("")

    lines.append("# --- tags ---")
    lines.append("labels = {}")
    lines.append("# namespace / instance_name / created_by tags come from the broker when it runs this module")
    return "\n".join(lines) + "\n"


def gen_broker_config(v):
    conn = v["connection"]

    lines = [
        "# GENERATED by scripts/gen-config.py from config/site-values.yaml — edit that",
        "# file and run `make gen-config` instead of editing this one.",
        "#",
        "#   csb serve --config hcs-broker.yaml",
        "#",
        "# Credentials stay in the environment (HCS_ACCESS_KEY / HCS_SECRET_KEY, or",
        "# HCS_DOMAIN_NAME / HCS_USER_NAME / HCS_USER_PASSWORD).",
        "",
        "hcs:",
        f"  cloud: {conn['cloud']}",
        f"  region: {conn['region']}",
        f"  project_name: {conn['project_name']}",
    ]
    if conn.get("auth_url"):
        lines.append(f"  auth_url: {conn['auth_url']}")
    lines.append(f"  insecure: {str(conn.get('insecure', False)).lower()}")
    lines.append("")
    return "\n".join(lines)


def main():
    with open(VALUES_FILE) as f:
        v = yaml.safe_load(f)

    missing = [s for s in SERVICES if s not in v["instances"]]
    if missing:
        sys.exit(f"site-values.yaml is missing instances for: {', '.join(missing)}")

    for key in ["cloud", "region", "project_name"]:
        if not v.get("connection", {}).get(key):
            sys.exit(
                f"site-values.yaml is missing connection.{key}.\n"
                "Your local copy predates a new required key - compare with\n"
                "config/site-values.yaml.example (diff config/site-values.yaml "
                "config/site-values.yaml.example), copy the new key in,\n"
                "or start fresh with `make site-values-reset`."
            )

    config = gen_broker_config(v)
    BROKER_CONFIG.write_text(config)
    print(f"wrote {BROKER_CONFIG.relative_to(ROOT)}")

    shared = [
        "# -----------------------------------------------------------------------------",
        "# Shared values for every module — GENERATED by scripts/gen-config.py from",
        "# config/site-values.yaml; edit that file and run `make gen-config`.",
        "# Pass it FIRST so per-module files can override:",
        "#   tofu apply -var-file=examples/shared.tfvars -var-file=examples/<svc>/<mod>.tfvars",
        "# -----------------------------------------------------------------------------",
        "",
        "# --- connection ---",
        kv("region", v["connection"]["region"]),
        kv("cloud", v["connection"]["cloud"]),
        kv("project_name", v["connection"]["project_name"]),
        "",
    ]
    shared_path = ROOT / "examples" / "shared.tfvars"
    shared_path.write_text("\n".join(shared))
    print(f"wrote {shared_path.relative_to(ROOT)}")

    for svc in SERVICES:
        out = ROOT / "examples" / svc / "provision.tfvars"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(gen_provision_tfvars(v, svc))
        print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
